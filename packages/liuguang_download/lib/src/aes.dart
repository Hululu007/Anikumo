  static Uint8List _expandKey(List<int> key) {
    if (key.length != 16) {
      throw ArgumentError('AES-128 key must be 16 bytes, got ${key.length}');
    }
    final w = Uint8List(176);
    w.setRange(0, 16, key);
    final temp = Uint8List(4);
    var pos = 16;
    var rconIter = 0;
    while (pos < 176) {
      temp.setRange(0, 4, w, pos - 4);
      if (pos % 16 == 0) {
        final t = temp[0];
        temp[0] = _sBox[temp[1]] ^ _rcon[rconIter++];
        temp[1] = _sBox[temp[2]];
        temp[2] = _sBox[temp[3]];
        temp[3] = _sBox[t];
      }
      for (var i = 0; i < 4; i++) {
        w[pos] = w[pos - 16] ^ temp[i];
        pos++;
      }
    }
    return w;
  }

  static int _mul(int a, int b) {
    var result = 0;
    var x = a;
    var y = b;
    while (y > 0) {
      if (y & 1 != 0) result ^= x;
      x = (x << 1) ^ (x & 0x80 != 0 ? 0x1b : 0);
      x &= 0xff;
      y >>= 1;
    }
    return result;
  }

  void _addRoundKey(Uint8List state, int round) {
    final offset = round * 16;
    for (var i = 0; i < 16; i++) {
      state[i] ^= _roundKeys[offset + i];
    }
  }

  static void _shiftRows(Uint8List s, {required bool inverse}) {
    final t = Uint8List.fromList(s);
    for (var row = 1; row < 4; row++) {
      for (var col = 0; col < 4; col++) {
        final src = inverse ? (col - row + 4) % 4 : (col + row) % 4;
        s[row + 4 * col] = t[row + 4 * src];
      }
    }
  }

  static void _mixColumns(Uint8List s, {required bool inverse}) {
    for (var col = 0; col < 4; col++) {
      final i = 4 * col;
      final a0 = s[i], a1 = s[i + 1], a2 = s[i + 2], a3 = s[i + 3];
      if (!inverse) {
        s[i] = _mul(a0, 2) ^ _mul(a1, 3) ^ a2 ^ a3;
        s[i + 1] = a0 ^ _mul(a1, 2) ^ _mul(a2, 3) ^ a3;
        s[i + 2] = a0 ^ a1 ^ _mul(a2, 2) ^ _mul(a3, 3);
        s[i + 3] = _mul(a0, 3) ^ a1 ^ a2 ^ _mul(a3, 2);
      } else {
        s[i] = _mul(a0, 14) ^ _mul(a1, 11) ^ _mul(a2, 13) ^ _mul(a3, 9);
        s[i + 1] = _mul(a0, 9) ^ _mul(a1, 14) ^ _mul(a2, 11) ^ _mul(a3, 13);
        s[i + 2] = _mul(a0, 13) ^ _mul(a1, 9) ^ _mul(a2, 14) ^ _mul(a3, 11);
        s[i + 3] = _mul(a0, 11) ^ _mul(a1, 13) ^ _mul(a2, 9) ^ _mul(a3, 14);
      }
    }
  }

  /// Encrypts one 16-byte block.
  Uint8List encryptBlock(List<int> block) {
    final s = Uint8List.fromList(block);
    _addRoundKey(s, 0);
    for (var round = 1; round < 10; round++) {
      for (var i = 0; i < 16; i++) {
        s[i] = _sBox[s[i]];
      }
      _shiftRows(s, inverse: false);
      _mixColumns(s, inverse: false);
      _addRoundKey(s, round);
    }
    for (var i = 0; i < 16; i++) {
      s[i] = _sBox[s[i]];
    }
    _shiftRows(s, inverse: false);
    _addRoundKey(s, 10);
    return s;
  }

  /// Decrypts one 16-byte block.
  Uint8List decryptBlock(List<int> block) {
    final s = Uint8List.fromList(block);
    _addRoundKey(s, 10);
    for (var round = 9; round >= 1; round--) {
      _shiftRows(s, inverse: true);
      for (var i = 0; i < 16; i++) {
        s[i] = _invSBox[s[i]];
      }
      _addRoundKey(s, round);
      _mixColumns(s, inverse: true);
    }
    _shiftRows(s, inverse: true);
    for (var i = 0; i < 16; i++) {
      s[i] = _invSBox[s[i]];
    }
    _addRoundKey(s, 0);
    return s;
  }

  /// CBC decryption with PKCS#7 unpadding — the HLS
  /// segment operation. Throws [FormatException] on a bad
  /// length or padding (a corrupt segment or wrong key).
  List<int> decryptCbc(List<int> data, List<int> iv) {
    if (iv.length != 16) throw ArgumentError('IV must be 16 bytes');
    if (data.isEmpty || data.length % 16 != 0) {
      throw const FormatException('ciphertext is not a multiple of 16');
    }
    final out = Uint8List(data.length);
    var previous = Uint8List.fromList(iv);
    for (var offset = 0; offset < data.length; offset += 16) {
      final block = data.sublist(offset, offset + 16);
      final plain = decryptBlock(block);
      for (var i = 0; i < 16; i++) {
        out[offset + i] = plain[i] ^ previous[i];
      }
      previous = Uint8List.fromList(block);
    }
    final pad = out.last;
    if (pad < 1 || pad > 16 || pad > out.length) {
      throw const FormatException('invalid PKCS#7 padding');
    }
    for (var i = out.length - pad; i < out.length; i++) {
      if (out[i] != pad) {
        throw const FormatException('invalid PKCS#7 padding');
      }
    }
    return out.sublist(0, out.length - pad);
  }

  /// CBC encryption with PKCS#7 padding (fixtures/tests).
  List<int> encryptCbc(List<int> data, List<int> iv) {
    if (iv.length != 16) throw ArgumentError('IV must be 16 bytes');
    final pad = 16 - (data.length % 16);
    final padded = Uint8List(data.length + pad);
    padded.setRange(0, data.length, data);
    for (var i = data.length; i < padded.length; i++) {
      padded[i] = pad;
    }
    final out = Uint8List(padded.length);
    var previous = Uint8List.fromList(iv);
    for (var offset = 0; offset < padded.length; offset += 16) {
      final block = Uint8List(16);
      for (var i = 0; i < 16; i++) {
        block[i] = padded[offset + i] ^ previous[i];
      }
      final cipher = encryptBlock(block);
      out.setRange(offset, offset + 16, cipher);
      previous = cipher;
    }
    return out;
  }
}

/// The default HLS IV for a segment: its media sequence
/// number as a 16-byte big-endian integer (RFC 8216 §5.2).
List<int> hlsSequenceIv(int sequence) {
  final iv = Uint8List(16);
  var value = sequence;
  for (var i = 15; i >= 8 && value > 0; i--) {
    iv[i] = value & 0xff;
    value >>= 8;
  }
  return iv;
}
